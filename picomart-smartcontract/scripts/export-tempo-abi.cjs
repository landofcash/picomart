const fs = require("node:fs");
const path = require("node:path");
const {keccak256} = require("ethers");
const root = path.resolve(__dirname,"..");
const artifact = JSON.parse(fs.readFileSync(path.join(root,"artifacts/contracts/Picomart.sol/Picomart.json"),"utf8"));
const debug = JSON.parse(fs.readFileSync(path.join(root,"artifacts/contracts/Picomart.sol/Picomart.dbg.json"),"utf8"));
const build = JSON.parse(fs.readFileSync(path.resolve(root,"artifacts/contracts/Picomart.sol",debug.buildInfo),"utf8"));
if (build.solcVersion !== "0.8.37" || build.input.settings.evmVersion !== "osaka" || !build.input.settings.viaIR) throw new Error("Unexpected Tempo compiler settings");
const getter = name => artifact.abi.find(item=>item.type === "function" && item.name === name);
const orderFields = getter("getOrder").outputs[0].components.map(({name,type})=>({name,type}));
const catalogFields = getter("catalogs").outputs.map(({name,type})=>({name,type}));
const source = fs.readFileSync(path.join(root,"contracts/Picomart.sol"),"utf8");
const names = /enum OrderState\s*\{([^}]+)\}/.exec(source)[1].split(",").map(value=>value.trim());
const states = Object.fromEntries(names.map((name,index)=>[name,index]));
const metadata = {compiler:build.solcLongVersion,evmVersion:build.input.settings.evmVersion,optimizer:build.input.settings.optimizer,
  viaIR:build.input.settings.viaIR,creationBytecodeHash:keccak256(artifact.bytecode),runtimeBytecodeHash:keccak256(artifact.deployedBytecode)};
const generated = "// Generated by picomart-smartcontract/scripts/export-tempo-abi.cjs. Do not edit.\n"+
  [["PICOMART_TEMPO_ABI",artifact.abi],["PICOMART_TEMPO_ORDER_FIELDS",orderFields],["PICOMART_TEMPO_CATALOG_FIELDS",catalogFields],
    ["PICOMART_TEMPO_ORDER_STATES",states],["PICOMART_TEMPO_BUILD",metadata]]
    .map(([name,value])=>`export const ${name} = ${JSON.stringify(value,null,2)} as const;\n`).join("\n");
const target = path.resolve(root,"../picomart-order-protocol/src/tempoContract.ts");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target,"utf8") !== generated) throw new Error("Tempo ABI export is stale; run npm run export:tempo");
  console.log("Tempo ABI, row fields and artifact hashes match the compiled contract.");
} else {
  fs.writeFileSync(target,generated);console.log("Generated isolated Tempo ABI, row fields and build hashes.");
}
